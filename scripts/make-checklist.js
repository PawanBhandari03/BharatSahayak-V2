// Regenerates scheme-data/VERIFICATION_CHECKLIST.md from schemes.json (one block per unverified scheme).
//   npm run checklist:schemes
const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, '../scheme-data');
const list = JSON.parse(fs.readFileSync(path.join(DIR, 'schemes.json'), 'utf8'));
const todo = list.filter((s) => !s.verified);
const done = list.length - todo.length;

const L = [];
L.push('# Scheme verification checklist', '');
L.push(`${done} of ${list.length} schemes are verified. ${todo.length} still need a person to check them. (Generated by \`npm run checklist:schemes\`; do not edit by hand.)`, '');
L.push('## How to verify one scheme (about 5 minutes)', '');
L.push('1. Open the **official page** (link below) in a browser. The government scheme portal needs a browser; it cannot be read by scripts.');
L.push('2. Compare **every line** in the block with the page: age, gender, state, work, category, income limit, land, BPL, amount, documents.');
L.push('3. If anything differs, fix that scheme in `scheme-data/schemes.json` first (use `null` when the page does not say).');
L.push('4. Run the command in the block. It marks the scheme verified, stores the page you checked and today\'s date.');
L.push('5. Run `npm run validate:schemes`, then commit.', '');
L.push('Only mark a scheme verified if you really compared it. Verified schemes are the ones shown to citizens in production.', '');
L.push('---', '');

todo.forEach((s, n) => {
  const el = s.eligibility;
  L.push(`### ${n + 1}. ${s.name.en} (\`${s.id}\`)`, '');
  L.push(`- [ ] Official page: ${s.officialUrl}`);
  L.push(`- Age: ${el.minAge ?? 'no minimum'} to ${el.maxAge ?? 'no maximum'}`);
  L.push(`- Gender: ${el.gender} · State: ${s.state} · Marital status: ${el.maritalStatus}`);
  L.push(`- Work: ${el.occupations.join(', ')} · Category: ${el.categories.join(', ')}`);
  L.push(`- Income limit: ${el.maxAnnualIncome ?? 'none'} · Needs land: ${el.requiresLand ?? 'not stated'} · Needs BPL card: ${el.requiresBPL ?? 'not stated'}`);
  L.push(`- Benefit: ${s.amount != null ? '₹' + s.amount.toLocaleString('en-IN') : 'no fixed amount'} (${s.frequency ?? 'n/a'}) — ${s.benefitSummary.en}`);
  L.push(`- Documents: ${s.documents.join('; ')}`);
  L.push(`- Then run: \`npm run verify:scheme -- ${s.id} --source <page you checked> --yes\``, '');
});

fs.writeFileSync(path.join(DIR, 'VERIFICATION_CHECKLIST.md'), L.join('\n'));
console.log(`Checklist written: ${todo.length} schemes to verify.`);
